package com.rusefi.maintenance.migration;

import com.opensr5.ConfigurationImage;
import com.opensr5.ConfigurationImageWithMeta;
import com.opensr5.ini.IniFileModel;
import com.rusefi.ini.reader.IniFileReaderUtil;
import com.rusefi.ini.reader.IniParsingException;
import com.rusefi.maintenance.CalibrationsHelper;
import com.rusefi.maintenance.CalibrationsInfo;
import com.rusefi.maintenance.TestCallbacks;
import com.rusefi.tune.xml.Constant;
import com.rusefi.tune.xml.Msq;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.io.IOException;
import java.util.Collections;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Synthetic lambda round-trip check: loading the same tune twice (merge onto a blank image, then
 * merge again onto the first result) must not change any field, in particular the lambda/AFR ones.
 *
 * Everything is synthetic - the ini and the tune are built in-test (the ini from a small text
 * fixture written to a temp dir, the msq generated by the console's own Msq.valueOf serialization),
 * so the test does not depend on the board tune or on a generated rusefi_*.ini being present.
 */
public class LambdaSecondLoadCheckTest {
    private static final String SIGNATURE = "rusEFI synthetic.2026.08.21.test-board.123456789";
    private static final int PAGE_SIZE = 64;

    // lambda/AFR-shaped fields: scalar lambda, scalar AFR (0.001 resolution), a boolean-ish bit
    // and a 2x2 lambda table - the shapes that previously drifted on double load.
    private static final List<String> LAMBDA_FIELDS = List.of("targetLambda", "afrScalar", "stoichEnabled", "lambdaTable");

    private static final String SYNTHETIC_INI = "" +
        "[TunerStudio]\n" +
        "\tsignature = \"" + SIGNATURE + "\"\n" +
        "[Constants]\n" +
        "\tnPages = 1\n" +
        "\tpageSize = " + PAGE_SIZE + "\n" +
        "\tochBlockSize = " + PAGE_SIZE + "\n" +
        "\tpageReadCommand = \"P%2i%2o%2c\"\n" +
        "\tpage = 1\n" +
        "\ttargetLambda = scalar, F32, 0, \"lambda\", 1, 0, 0.5, 2.0, 3\n" +
        "\tafrScalar = scalar, F32, 4, \"AFR\", 0.001, 0, 8, 22, 3\n" +
        "\tstoichEnabled = bits, U32, 32, [0:0], \"false\", \"true\"\n" +
        "\tlambdaTable = array, U16, 8, [2x2], \"lambda\", 0.001, 0, 0, 2, 3\n";

    private static IniFileModel readSyntheticIni(Path dir) throws IOException, IniParsingException {
        Path iniPath = dir.resolve("synthetic.ini");
        Files.write(iniPath, SYNTHETIC_INI.getBytes(StandardCharsets.UTF_8));
        return IniFileReaderUtil.readIniFileChecked(iniPath.toString());
    }

    /** Builds the source tune by encoding plain values into an image and serializing back via the console's own Msq.valueOf. */
    private static Msq buildSourceTune(IniFileModel ini) {
        ConfigurationImage image = new ConfigurationImage(PAGE_SIZE);
        com.rusefi.tune.ConfigurationImageGetterSetter2.setValue(
            ini.findIniField("targetLambda").orElseThrow(), image,
            new Constant("targetLambda", "lambda", "1.000", "3"));
        com.rusefi.tune.ConfigurationImageGetterSetter2.setValue(
            ini.findIniField("afrScalar").orElseThrow(), image,
            new Constant("afrScalar", "AFR", "14.700", "3"));
        com.rusefi.tune.ConfigurationImageGetterSetter2.setValue(
            ini.findIniField("stoichEnabled").orElseThrow(), image,
            new Constant("stoichEnabled", "", "\"true\"", "0"));
        com.rusefi.tune.ConfigurationImageGetterSetter2.setValue(
            ini.findIniField("lambdaTable").orElseThrow(), image,
            new Constant("lambdaTable", "lambda", "\n0.800 0.900\n1.000 1.100", "3", "2", "2"));
        return Msq.valueOf(image, PAGE_SIZE, SIGNATURE, ini);
    }

    private static CalibrationsInfo blankCalibrations(IniFileModel ini) {
        ConfigurationImage blank = new ConfigurationImage(PAGE_SIZE);
        return new CalibrationsInfo(ini, ConfigurationImageWithMeta.valueOf(ini, blank));
    }

    @Test
    public void secondLoadOfSameTuneProducesNoLambdaDiff(@TempDir Path dir) throws Throwable {
        IniFileModel ini = readSyntheticIni(dir);
        Msq sourceTune = buildSourceTune(ini);
        Map<String, Constant> sourceValues = sourceTune.getConstantsAsMap();

        // "first load": merge the tune onto a blank image (post-recovery state)
        CalibrationsHelper.MergeResult first = CalibrationsHelper.mergeCalibrationsWithPartialFailure(
            ini, sourceTune, blankCalibrations(ini), new TestCallbacks(), Collections.emptySet());
        assertTrue(first.mergedCalibrations.isPresent(), "first merge must produce calibrations, failed fields: " + first.failedFields);
        ConfigurationImage image1 = first.mergedCalibrations.get().getImage().getConfigurationImage();
        Map<String, Constant> firstValues = first.mergedCalibrations.get().generateMsq().getConstantsAsMap();

        // "second load": merge the same tune onto the first-load image. An empty result is the
        // expected idempotent outcome ("nothing to update"); if something IS re-applied, the lambda
        // fields must be byte-identical - that is the regression this harness guards against.
        CalibrationsHelper.MergeResult second = CalibrationsHelper.mergeCalibrationsWithPartialFailure(
            ini, sourceTune,
            new CalibrationsInfo(ini, ConfigurationImageWithMeta.valueOf(ini, image1)),
            new TestCallbacks(), Collections.emptySet());

        for (String field : LAMBDA_FIELDS) {
            Constant original = sourceValues.get(field);
            assertNotNull(original, "synthetic tune must carry " + field);
            assertEquals(original.getValue(), firstValues.get(field).getValue(),
                field + " must round-trip the first load");
        }
        if (second.mergedCalibrations.isPresent()) {
            Map<String, Constant> secondValues = second.mergedCalibrations.get().generateMsq().getConstantsAsMap();
            for (String field : LAMBDA_FIELDS) {
                assertEquals(sourceValues.get(field).getValue(), secondValues.get(field).getValue(),
                    field + " must not change on the second load");
            }
        }
    }
}
